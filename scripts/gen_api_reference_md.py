#!/usr/bin/env python3
"""Generate docs/api_reference.md from docs/api_reference.rst and Doxygen XML.

docs/api_reference.rst only holds Breathe directives, so tools that read the
repository as files (such as Context7) never see the signatures or doc
comments behind them. This script expands each directive into Markdown, in the
.rst file's order, from the XML that ./scripts/build_docs.sh generates.

Usage:
    ./scripts/build_docs.sh
    python3 scripts/gen_api_reference_md.py [--xml DIR] [--check]

--check exits non-zero if docs/api_reference.md is out of date.
"""

import argparse
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RST = ROOT / "docs" / "api_reference.rst"
OUT = ROOT / "docs" / "api_reference.md"
DEFAULT_XML = ROOT / "build" / "docs" / "doxygen" / "xml"

HEADER = (
    "<!-- Generated by scripts/gen_api_reference_md.py from docs/api_reference.rst"
    " and the doc comments in the source. Don't edit this file by hand: change the"
    " doc comments, then run ./scripts/build_docs.sh and"
    " python3 scripts/gen_api_reference_md.py. -->"
)

DIRECTIVE = re.compile(r"^\.\. doxygen(function|define|typedef|struct)::\s*(\S+)\s*$")
SIMPLESECT_TITLES = {
    "return": "Returns",
    "see": "See also",
    "note": "Note",
    "warning": "Warning",
    "attention": "Attention",
    "pre": "Precondition",
    "post": "Postcondition",
    "since": "Since",
    "deprecated": "Deprecated",
}


def load_xml(xml_dir):
    members, structs = {}, {}
    for path in sorted(xml_dir.glob("*.xml")):
        if path.name == "index.xml":
            continue
        root = ET.parse(path).getroot()
        for compound in root.iter("compounddef"):
            if compound.get("kind") == "struct":
                structs[compound.findtext("compoundname")] = compound
        for member in root.iter("memberdef"):
            key = (member.get("kind"), member.findtext("name"))
            # Prefer the declaration in note.h over a definition elsewhere.
            in_header = member.find("location").get("file", "").endswith("note.h")
            if key not in members or in_header:
                members[key] = member
    return members, structs


def text(elem):
    """Plain text of an element, as a C declaration would read."""
    return re.sub(r"\s+", " ", "".join(elem.itertext())).strip() if elem is not None else ""


def tidy_pointer(sig):
    sig = re.sub(r"\s+\*", " *", sig)
    return re.sub(r"\*\s+(?=[\w(])", "*", sig)


def inline(elem):
    """Markdown for an element's inline content, skipping block children."""
    out = [elem.text or ""]
    for child in elem:
        if child.tag in BLOCK_TAGS:
            pass
        elif child.tag == "computeroutput":
            out.append(f"`{text(child)}`")
        elif child.tag in ("bold",):
            out.append(f"**{inline(child).strip()}**")
        elif child.tag in ("emphasis",):
            out.append(f"*{inline(child).strip()}*")
        elif child.tag == "ulink":
            out.append(f"[{inline(child).strip()}]({child.get('url')})")
        elif child.tag == "linebreak":
            out.append("\n")
        else:
            out.append(inline(child))
        out.append(child.tail or "")
    return "".join(out)


def blocks(elem):
    """Markdown blocks for a description element (brief or detailed)."""
    result = []
    for para in elem.iter("para") if elem is not None else []:
        if para in _seen:
            continue
        _seen.add(para)
        line = re.sub(r"[ \t]+", " ", inline(para)).strip()
        if line:
            result.append(line)
        for child in para:
            if child.tag in BLOCK_TAGS:
                result.append(BLOCK_TAGS[child.tag](child))
    return [b for b in result if b]


def param_list(elem):
    title = {"param": "Parameters", "retval": "Return values", "exception": "Exceptions"}.get(
        elem.get("kind"), "Parameters")
    lines = [f"**{title}:**", ""]
    for item in elem.findall("parameteritem"):
        names = ", ".join(f"`{text(n)}`" for n in item.iter("parametername"))
        desc = " ".join(blocks(item.find("parameterdescription")))
        lines.append(f"- {names}: {desc}".rstrip(": "))
    return "\n".join(lines)


def simplesect(elem):
    title = SIMPLESECT_TITLES.get(elem.get("kind"), elem.get("kind", "").capitalize())
    return f"**{title}:** " + " ".join(blocks(elem))


def code_block(elem):
    lines = []
    for codeline in elem.iter("codeline"):
        parts = []
        for node in codeline.iter():
            if node.tag == "sp":
                parts.append(" ")
            elif node.text and node.tag not in ("codeline", "highlight"):
                parts.append(node.text)
            elif node.tag == "highlight" and node.text:
                parts.append(node.text)
            if node is not codeline and node.tail:
                parts.append(node.tail)
        lines.append("".join(parts).rstrip())
    return "```c\n" + "\n".join(lines) + "\n```"


def item_list(elem, ordered=False):
    lines = []
    for i, item in enumerate(elem.findall("listitem"), 1):
        bullet = f"{i}." if ordered else "-"
        lines.append(f"{bullet} " + " ".join(blocks(item)))
    return "\n".join(lines)


BLOCK_TAGS = {
    "parameterlist": param_list,
    "simplesect": simplesect,
    "programlisting": code_block,
    "itemizedlist": item_list,
    "orderedlist": lambda e: item_list(e, ordered=True),
}
_seen = set()


def description(elem):
    return blocks(elem.find("briefdescription")) + blocks(elem.find("detaileddescription"))


def signature(kind, member):
    name = member.findtext("name")
    if kind == "function":
        sig = f"{text(member.find('type'))} {name}{member.findtext('argsstring') or ''};"
    elif kind == "typedef":
        # A function-pointer typedef splits around the name: type "size_t(*",
        # argsstring ")(const char *text)".
        type_, args = text(member.find("type")), member.findtext("argsstring") or ""
        if type_.endswith("(*"):
            sig = f"typedef {type_[:-2].rstrip()} (*{name}{args};"
        else:
            sig = f"typedef {type_} {name}{args};"
    else:  # define
        params = [p.findtext("defname") for p in member.findall("param")]
        sig = f"#define {name}" + (f"({', '.join(params)})" if member.find("param") is not None else "")
        init = text(member.find("initializer"))
        if init and "\n" not in init and len(init) <= 80:
            sig += f" {init}"
    return tidy_pointer(sig)


def render_member(kind, name, members):
    member = members.get((kind, name))
    if member is None:
        raise SystemExit(f"error: {kind} {name} is in {RST.name} but not in the Doxygen XML")
    parts = [f"#### {name}", f"```c\n{signature(kind, member)}\n```", *description(member)]
    return "\n\n".join(parts)


def render_struct(name, structs):
    compound = structs.get(name)
    if compound is None:
        raise SystemExit(f"error: struct {name} is in {RST.name} but not in the Doxygen XML")
    parts = [f"#### {name}", *description(compound)]
    fields = []
    for member in compound.iter("memberdef"):
        if member.get("kind") != "variable":
            continue
        decl = tidy_pointer(f"{text(member.find('type'))} {member.findtext('name')}"
                            f"{member.findtext('argsstring') or ''}")
        desc = " ".join(description(member))
        fields.append(f"- `{decl}`" + (f": {desc}" if desc else ""))
    if fields:
        parts.append("**Fields:**\n\n" + "\n".join(fields))
    return "\n\n".join(parts)


def generate(xml_dir):
    members, structs = load_xml(xml_dir)
    lines = RST.read_text().splitlines()
    out, para = [HEADER], []

    def flush():
        if para:
            out.append(" ".join(para))
            para.clear()

    i = 0
    while i < len(lines):
        line, nxt = lines[i], lines[i + 1] if i + 1 < len(lines) else ""
        if re.fullmatch(r"\*{3,}", line) and i + 2 < len(lines):
            flush()
            out.append(f"# {lines[i + 1].strip()}")
            i += 3
            continue
        if line.strip() and re.fullmatch(r"=+", nxt):
            flush()
            out.append(f"## {line.strip()}")
            i += 2
            continue
        if line.strip() and re.fullmatch(r"-+", nxt):
            flush()
            out.append(f"### {line.strip()}")
            i += 2
            continue
        match = DIRECTIVE.match(line)
        if match:
            flush()
            kind, name = match.groups()
            out.append(render_struct(name, structs) if kind == "struct"
                       else render_member(kind, name, members))
        elif line.startswith(".. ") or line.startswith("   :"):
            flush()  # other directives and their options (e.g. contents)
        elif line.strip():
            para.append(line.strip())
        else:
            flush()
        i += 1
    flush()
    return "\n\n".join(out).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--xml", type=Path, default=DEFAULT_XML, help="Doxygen XML directory")
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args()
    if not (args.xml / "index.xml").is_file():
        raise SystemExit(f"error: no Doxygen XML in {args.xml}; run ./scripts/build_docs.sh first")
    markdown = generate(args.xml)
    if args.check:
        if not OUT.is_file() or OUT.read_text() != markdown:
            print(f"{OUT.relative_to(ROOT)} is out of date; run "
                  "python3 scripts/gen_api_reference_md.py and commit the result.", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(markdown)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
